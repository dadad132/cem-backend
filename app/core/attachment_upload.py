"""Validation shared by the web attachment upload routes.

Browsers send a filename and a MIME type, both of which the caller controls.
Neither is trusted here: the stored name is always generated by the route and
the extension comes from inspecting the bytes (photos/PDF) or from a short
allowlist of boring document types.
"""
from __future__ import annotations

import re
from pathlib import Path

MAX_ATTACHMENT_BYTES = 10 * 1024 * 1024
MAX_ATTACHMENTS_PER_UPLOAD = 20
MAX_FILENAME_LENGTH = 120

# Keep only characters that are harmless in an HTML attribute, a JS string and
# a Content-Disposition header. Quotes and angle brackets are the dangerous
# ones: they have broken out of all three contexts in this app before.
_UNSAFE_FILENAME_CHARS = re.compile(r'[^A-Za-z0-9._ ()-]')

# Extensions we accept when the bytes do not identify a photo or a PDF. The
# stored extension is taken from this mapping, never from the uploaded name.
DOCUMENT_TYPES = {
    '.txt': 'text/plain',
    '.doc': 'application/msword',
    '.docx': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    '.xls': 'application/vnd.ms-excel',
    '.xlsx': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    '.zip': 'application/zip',
    '.rar': 'application/vnd.rar',
}


def photo_type(data: bytes):
    """(mime type, extension) of a photo judged by its bytes, or None.

    SVG and HTML are deliberately absent: they can carry script, and an
    uploaded file is served from our own origin.
    """
    if data[:3] == b'\xff\xd8\xff':
        return 'image/jpeg', '.jpg'
    if data[:8] == b'\x89PNG\r\n\x1a\n':
        return 'image/png', '.png'
    if data[:6] in (b'GIF87a', b'GIF89a'):
        return 'image/gif', '.gif'
    if data[:4] == b'RIFF' and data[8:12] == b'WEBP':
        return 'image/webp', '.webp'
    if data[4:8] == b'ftyp' and data[8:12] in (b'heic', b'heix', b'hevc', b'hevx', b'mif1', b'msf1'):
        return 'image/heic', '.heic'
    return None


def clean_upload_name(filename: str | None, fallback: str = 'file') -> str:
    """Basename of a browser-supplied filename, safe in HTML, JS and headers.

    Windows and POSIX separators are both treated as separators, then every
    character outside a small allowlist is replaced. This keeps a name from
    forging a header, an HTML attribute or a JS string in attachment previews.
    """
    name = (filename or '').replace('\\', '/').rsplit('/', 1)[-1]
    name = _UNSAFE_FILENAME_CHARS.sub('_', name)
    return name.strip().strip('.')[:MAX_FILENAME_LENGTH] or fallback


def validate_attachment(data: bytes, filename: str | None, declared_type: str | None = None):
    """Return ``(MIME type, stored extension)`` or None.

    None means the file must not be written: empty, oversized, an unknown type,
    or a declared type that contradicts a document's extension. The browser's
    filename is only used as an extension hint for documents; the stored name
    is generated by the caller so traversal names never reach the filesystem.
    """
    if not data or len(data) > MAX_ATTACHMENT_BYTES:
        return None

    name = clean_upload_name(filename)
    extension = Path(name).suffix.lower()
    # Documents are identified by their allowlisted extension plus a matching
    # declared type (they are served as downloads, never executed in-page).
    kind = photo_type(data)
    if kind:
        mime, stored_extension = kind
    elif data[:5] == b'%PDF-' and extension == '.pdf':
        mime, stored_extension = 'application/pdf', '.pdf'
    elif extension in DOCUMENT_TYPES and (
        not declared_type
        or declared_type == 'application/octet-stream'
        or declared_type == DOCUMENT_TYPES[extension]
    ):
        mime, stored_extension = DOCUMENT_TYPES[extension], extension
    else:
        return None
    return mime, stored_extension
